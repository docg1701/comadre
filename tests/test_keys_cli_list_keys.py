"""End-to-end CLI tests for ``comadre-keys list-keys`` (Story 1.3).

Lean by design (test-suite review 2026-04-25): one populated table
test, one filter test, one JSON shape test, one empty-state test.
Per-status / per-billing-mode / per-filter parametrize variants
deleted; the underlying SQL is exercised once and trusted.
"""

from __future__ import annotations

import json
import re
import sqlite3
from datetime import date
from pathlib import Path

import pytest
from cryptography.fernet import Fernet
from typer.testing import CliRunner

from comadre.keys.cli import _clock
from comadre.keys.cli.app import app
from tests._keys_cli_helpers import buffers as _buffers
from tests._keys_cli_helpers import clear_buffers as _clear_buffers

runner = CliRunner()


@pytest.fixture()
def env(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> dict[str, str]:
    key = Fernet.generate_key().decode()
    db_path = tmp_path / "registry.db"
    monkeypatch.setenv("KEY_REGISTRY_DB_PATH", str(db_path))
    monkeypatch.setenv("KEY_REGISTRY_ENCRYPTION_KEY", key)
    monkeypatch.setattr(_clock, "resolve_today_in_tz", lambda _tz: date(2026, 4, 16))
    return {"db_path": str(db_path), "key": key}


def _seed_customer(env: dict[str, str]) -> str:
    _clear_buffers()
    result = runner.invoke(
        app,
        [
            "create-customer",
            "--name",
            "Helena",
            "--email",
            "h@x.com",
            "--cpf",
            "123.456.789-09",
        ],
    )
    assert result.exit_code == 0, result.output
    stdout, _ = _buffers()
    match = re.search(r"cust_[0-9a-z]{26}", stdout)
    assert match is not None
    _clear_buffers()
    return match.group(0)


def _issue_key(env: dict[str, str], customer_id: str) -> None:
    _clear_buffers()
    runner.invoke(
        app, ["issue-key", "--customer", customer_id, "--rpm", "60", "--price", "149"]
    )
    _clear_buffers()


def _raw_insert_key(
    env: dict[str, str], customer_id: str, *, status: str, key_prefix: str
) -> None:
    from comadre.keys.db import generate_key_id

    key_id = generate_key_id()
    conn = sqlite3.connect(env["db_path"])
    try:
        conn.execute(
            "INSERT INTO api_key (id, customer_id, key_hash, key_prefix, "
            "rate_limit_rpm, status, billing_mode, price_monthly, paid_until, "
            "created_at, last_used_at, notes) VALUES "
            "(?, ?, ?, ?, 60, ?, 'manual', 149.0, NULL, "
            "'2026-04-16T12:00:00Z', NULL, '')",
            (
                key_id,
                customer_id,
                key_id.replace("key_", "").ljust(64, "0"),
                key_prefix,
                status,
            ),
        )
        conn.commit()
    finally:
        conn.close()


def test_list_keys_empty_db_prints_hint(env: dict[str, str]) -> None:
    """First-run UX: empty DB emits the 'create-customer' hint."""
    result = runner.invoke(app, ["list-keys"])
    stdout, _ = _buffers()
    assert result.exit_code == 0
    assert "comadre-keys issue-key" in stdout


def test_list_keys_populated_table_shows_all_statuses(env: dict[str, str]) -> None:
    """Happy path: table renders every issued key, regardless of status."""
    cid = _seed_customer(env)
    _issue_key(env, cid)
    _raw_insert_key(env, cid, status="suspended", key_prefix="SUSP1234")
    _raw_insert_key(env, cid, status="revoked", key_prefix="REVK1234")

    result = runner.invoke(app, ["list-keys"])
    stdout, _ = _buffers()
    assert result.exit_code == 0
    assert "SUSP1234" in stdout
    assert "REVK1234" in stdout
    # Non-list contract: notes column NOT shown in table.
    assert "Notes" not in stdout


def test_list_keys_status_filter_narrows_rows(env: dict[str, str]) -> None:
    """``--status suspended`` returns only suspended rows."""
    cid = _seed_customer(env)
    _issue_key(env, cid)  # active
    _raw_insert_key(env, cid, status="suspended", key_prefix="SUSP1234")

    result = runner.invoke(app, ["list-keys", "--status", "suspended"])
    stdout, _ = _buffers()
    assert result.exit_code == 0
    assert "SUSP1234" in stdout
    # The active key's prefix is randomly generated by issue-key, so we
    # assert via the row count: only one row, only the suspended row.
    assert stdout.count("suspended") >= 1


def test_list_keys_format_json_emits_array(env: dict[str, str]) -> None:
    """Machine consumers depend on a JSON array shape, not table text."""
    cid = _seed_customer(env)
    _issue_key(env, cid)

    result = runner.invoke(app, ["list-keys", "--format", "json"])
    stdout, _ = _buffers()
    assert result.exit_code == 0
    parsed = json.loads(stdout)
    assert isinstance(parsed, list)
    assert len(parsed) == 1
    row = parsed[0]
    assert row["status"] == "active"
    assert row["billing_mode"] == "manual"
    # No key_hash leak.
    assert "key_hash" not in row
